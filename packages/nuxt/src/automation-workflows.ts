import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export function writeAutomationWorkflows(rootDir: string): string {
  const directory = join(rootDir, '.cloudconfig')
  mkdirSync(directory, { recursive: true })
  const entry = join(directory, 'automation-workflows.ts')
  writeFileSync(
    entry,
    `// Generated by @cloudconfig/nuxt. Do not edit.
import { sleep } from 'workflow'
import { start } from 'workflow/api'
import type { AutomationIdentity } from '@cloudconfig/core/automations'
import type { AutomationScheduleIdentity } from '@cloudconfig/core/automations/service'
import { tick, nextSchedule, fireSchedule, trackSchedule } from './automation-steps'
export async function run(input: AutomationIdentity) {
  'use workflow'
  for (;;) {
    const result = await tick(input)
    if (['succeeded', 'failed', 'cancelled'].includes(result.status)) return result
    if (result.wakeAt) await sleep(new Date(result.wakeAt))
    else await sleep(result.status === 'waiting' ? '60 seconds' : '1 second')
  }
}
export async function schedule(input: AutomationScheduleIdentity) {
  'use workflow'
  const current = await nextSchedule(input)
  if (!current?.dueAt) return
  await sleep(new Date(current.dueAt))
  await fireSchedule(input, current.dueAt)
  const following = await nextSchedule(input)
  if (!following?.dueAt) return
  const next = await start(schedule, [input])
  await trackSchedule(input, next.runId, following.dueAt)
}
`,
  )
  writeFileSync(
    join(directory, 'automation-steps.ts'),
    `// Generated by @cloudconfig/nuxt. Do not edit.
import type { AutomationIdentity } from '@cloudconfig/core/automations'
import type { AutomationScheduleIdentity } from '@cloudconfig/core/automations/service'
import { automationService, bindPlatforms } from './workload-platforms'
export async function tick(input: AutomationIdentity) {
  'use step'
  bindPlatforms()
  return automationService().runtime.tick(input)
}
export async function nextSchedule(input: AutomationScheduleIdentity) {
  'use step'
  bindPlatforms()
  return automationService().schedule(input)
}
export async function fireSchedule(input: AutomationScheduleIdentity, dueAt: string) {
  'use step'
  bindPlatforms()
  await automationService().fire({ ...input, dueAt })
}
export async function trackSchedule(input: AutomationScheduleIdentity, id: string, dueAt: string) {
  'use step'
  bindPlatforms()
  await automationService().trackSchedule(input, id, dueAt)
}
`,
  )
  return entry
}

/** Bind lazy factories in both app requests and Workflow step workers, including cross-workload calls. */
export function writeWorkloadPlatforms(options: {
  rootDir: string
  configPath: string
  agentEntry?: string
  automationEntry?: string
}): string {
  const entry = join(options.rootDir, '.cloudconfig', 'workload-platforms.ts')
  const lines = [
    `// Generated by @cloudconfig/nuxt. Do not edit.`,
    `import { resolveConfigExport } from '@cloudconfig/core'`,
    `import * as configModule from ${JSON.stringify(options.configPath)}`,
  ]
  if (options.agentEntry) {
    lines.push(
      `import agentHost from ${JSON.stringify(options.agentEntry)}`,
      `import * as agentWorkflows from './agent-workflows'`,
      `import { provideAgentPlatform } from '@cloudconfig/core/agents/platform'`,
      `import { vercelAgentPlatform } from '@cloudconfig/core/agents/vercel'`,
    )
  }
  if (options.automationEntry) {
    lines.push(
      `import sourceHost from ${JSON.stringify(options.automationEntry)}`,
      `import * as automationWorkflows from './automation-workflows'`,
      `import { withConnectAutomations } from '@cloudconfig/core/automations/connect'`,
      `import { provideAutomationPlatform } from '@cloudconfig/core/automations'`,
      `import { vercelAutomationService } from '@cloudconfig/core/automations/vercel'`,
      `let service: ReturnType<typeof vercelAutomationService> | undefined`,
      `export function automationService() {`,
      `  if (service) return service`,
      `  const config = resolveConfigExport(configModule, 'cloud.config.ts')`,
      `  const host = withConnectAutomations(sourceHost, config)`,
      `  service = vercelAutomationService({ host, config, workflows: automationWorkflows })`,
      `  return service`,
      `}`,
    )
  }
  lines.push(`export function bindPlatforms() {`)
  if (options.agentEntry) {
    lines.push(
      `  provideAgentPlatform(() => vercelAgentPlatform({ host: agentHost, config: resolveConfigExport(configModule, 'cloud.config.ts'), workflows: agentWorkflows }))`,
    )
  }
  if (options.automationEntry) {
    lines.push(`  provideAutomationPlatform(() => automationService().platform)`)
  }
  lines.push(`}`)
  writeFileSync(entry, lines.join('\n'))
  return entry
}
