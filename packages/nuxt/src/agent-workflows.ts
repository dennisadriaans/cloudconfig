import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** Keep directives in consumer source: the official Workflow compiler owns their transformation. */
export function writeAgentWorkflows(options: {
  rootDir: string
  hostEntry: string
  configPath: string
}): string {
  const directory = join(options.rootDir, '.cloudconfig')
  mkdirSync(directory, { recursive: true })
  const path = join(directory, 'agent-workflows.ts')
  writeFileSync(
    path,
    `// Generated by @cloudconfig/nuxt. Do not edit.
import { sleep } from 'workflow'
import { start } from 'workflow/api'
import type { NativeAgentRun, NativeAgentSchedule } from '@cloudconfig/core/agents/durable'
import { tick, nextSchedule, fireSchedule, trackSchedule } from './agent-steps'
export async function run(input: NativeAgentRun) {
  'use workflow'
  for (;;) {
    const result = await tick(input)
    if (result.status === 'succeeded' || result.status === 'failed') return result
    await sleep(result.status === 'waiting' ? '60 seconds' : '1 second')
  }
}
export async function schedule(input: NativeAgentSchedule) {
  'use workflow'
  const current = await nextSchedule(input)
  if (!current?.dueAt) return
  await sleep(new Date(current.dueAt))
  await fireSchedule(input, current.dueAt)
  const following = await nextSchedule(input)
  if (!following?.dueAt) return
  const next = await start(schedule, [input])
  await trackSchedule(input, next.runId, following.dueAt)
}
`,
  )
  writeFileSync(
    join(directory, 'agent-steps.ts'),
    `// Generated by @cloudconfig/nuxt. Do not edit.
import { resolveConfigExport } from '@cloudconfig/core'
import { vercelAgentRuntime } from '@cloudconfig/core/agents/vercel'
import type { NativeAgentRun, NativeAgentSchedule } from '@cloudconfig/core/agents/durable'
import host from ${JSON.stringify(options.hostEntry)}
import * as configModule from ${JSON.stringify(options.configPath)}
import { bindPlatforms } from './workload-platforms'
function runtime() {
  bindPlatforms()
  return vercelAgentRuntime(host, resolveConfigExport(configModule, 'cloud.config.ts'))
}
export async function tick(input: NativeAgentRun) {
  'use step'
  return runtime().tick(input)
}
export async function nextSchedule(input: NativeAgentSchedule) {
  'use step'
  return runtime().schedule(input)
}
export async function fireSchedule(input: NativeAgentSchedule, dueAt: string) {
  'use step'
  await runtime().fire({ ...input, dueAt })
}
export async function trackSchedule(input: NativeAgentSchedule, id: string, dueAt: string) {
  'use step'
  await runtime().trackSchedule(input, id, dueAt)
}
`,
  )
  return path
}
