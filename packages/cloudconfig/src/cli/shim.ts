/**
 * Writes the `.cloudconfig/` shim that lets drizzle-kit generate migrations from
 * a config it can't see directly. drizzle-kit inspects the *exported Table
 * values* of the schema module, so we emit a module that compiles the config's
 * tables and re-exports each one by name.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import type { AnyConfig } from '../index.js'
import { resolveProjectConfig } from '../shared/project-config.js'
import { AUTH_MODEL_NAMES, ORGANIZATION_MODEL_NAMES, resolveAuth } from '../shared/auth-resolve.js'
import { resolveConnect } from '../shared/connect-resolve.js'
import { CONNECT_MODEL_NAMES } from '../server/compile/connect-tables.js'

export interface ShimPaths {
  dir: string
  schemaPath: string
  drizzleConfigPath: string
}

export function writeShim(
  projectDir: string,
  configPath: string,
  config: AnyConfig,
  migrationsDir: string,
): ShimPaths {
  const dir = join(projectDir, '.cloudconfig')
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true })

  // The auth tables are compiled models too, and drizzle-kit only diffs what
  // the schema module exports by name — miss them here and `cloudconfig db generate`
  // would quietly drop sign-in from every migration.
  const auth = resolveAuth(config)
  const authNames = auth
    ? [
        ...AUTH_MODEL_NAMES,
        ...(auth.organizations ? ORGANIZATION_MODEL_NAMES : []),
        ...(auth.twoFactor ? ['twoFactor'] : []),
        ...(auth.twoFactor && auth.twoFactor.passkey !== false ? ['passkey'] : []),
        ...(auth.scim && auth.organizations ? ['scimToken', 'scimIdentity'] : []),
      ]
    : []
  const connectNames = resolveConnect(config) ? [...CONNECT_MODEL_NAMES] : []
  const modelNames = [...authNames, ...connectNames, ...Object.keys(config.models)]
  const rel = relativeImport(dir, configPath)

  // A config may be exported as `config` or as a default export; both are valid
  // to the loader, so the shim must accept either.
  const schema = `// Generated by "cloudconfig db generate" — do not edit.
import * as configModule from '${rel}'
import { resolveConfigExport } from '@cloudconfig/core'
import { compileTables } from '@cloudconfig/core/server'

const config = resolveConfigExport(configModule, ${JSON.stringify(configPath)})
const tables = compileTables(config)
${modelNames.map((modelName) => `export const ${modelName} = tables['${modelName}']`).join('\n')}
`
  const schemaPath = join(dir, 'schema.ts')
  writeFileSync(schemaPath, schema)

  // Paths are relative to projectDir (drizzle-kit's cwd), not the config file.
  // Absolute out/schema paths break iterative generate (meta snapshot resolution).
  const schemaRel = './.cloudconfig/schema.ts'
  const outRel = relative(projectDir, join(projectDir, migrationsDir)).split('\\').join('/')
  const out = outRel.startsWith('.') ? outRel : `./${outRel}`
  const drizzleConfig = `// Generated by "cloudconfig db generate" — do not edit.
import { defineConfig } from 'drizzle-kit'

export default defineConfig({
  dialect: 'sqlite',
  schema: ${JSON.stringify(schemaRel)},
  out: ${JSON.stringify(out)},
})
`
  const drizzleConfigPath = join(dir, 'drizzle.config.ts')
  writeFileSync(drizzleConfigPath, drizzleConfig)

  return { dir, schemaPath, drizzleConfigPath }
}

function relativeImport(fromDir: string, toFile: string): string {
  let rel = relative(fromDir, toFile).split('\\').join('/')
  if (!rel.startsWith('.')) rel = `./${rel}`
  // strip the .ts extension so bundlers/jiti resolve it consistently
  return rel.replace(/\.ts$/, '')
}

export function migrationsDirFor(config: AnyConfig): string {
  return resolveProjectConfig(config).migrationsDir
}

export { resolve }
